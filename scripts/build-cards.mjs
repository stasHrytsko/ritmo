// Turns docs/weekly-cards.md (the editorial source) into the typed bank the app
// ships: src/domain/weeklyCards.data.ts. Run with `npm run cards`.
import { readFileSync, writeFileSync } from 'node:fs';

const source = readFileSync(new URL('../docs/weekly-cards.md', import.meta.url), 'utf8');
const TIERS = { 'Лёгкие': 'easy', 'Средние': 'medium', 'Сложные': 'hard' };

const cards = [];
let tier = null;
let current = null;

const flush = () => {
  if (current) cards.push({ ...current, text: current.text.replace(/\s+/g, ' ').trim() });
  current = null;
};

for (const line of source.split('\n')) {
  const heading = line.match(/^### (.+)$/);
  if (heading) {
    flush();
    tier = TIERS[heading[1].trim()] ?? null;
    continue;
  }
  if (!tier) continue;
  if (/^## /.test(line)) { flush(); tier = null; continue; }
  const item = line.match(/^- \*\*(.+?)\*\* — (.*)$/);
  if (item) {
    flush();
    current = { id: `${tier}:${item[1].trim()}`, tier, title: item[1].trim(), text: item[2] };
  } else if (current && /^\s+\S/.test(line)) {
    current.text += ` ${line.trim()}`;
  } else if (current && line.trim() === '') {
    flush();
  }
}
flush();

const ids = new Set();
for (const card of cards) {
  if (ids.has(card.id)) throw new Error(`Duplicate card: ${card.id}`);
  ids.add(card.id);
}

const body = cards.map((card) => `  ${JSON.stringify(card)}`).join(',\n');
writeFileSync(
  new URL('../src/domain/weeklyCards.data.ts', import.meta.url),
  `// Generated by scripts/build-cards.mjs from docs/weekly-cards.md. Do not edit.\nimport type { WeeklyCard } from './weeklyCards';\n\nexport const WEEKLY_CARDS: readonly WeeklyCard[] = [\n${body}\n];\n`
);
const count = (t) => cards.filter((card) => card.tier === t).length;
console.log(`cards: ${cards.length} (easy ${count('easy')}, medium ${count('medium')}, hard ${count('hard')})`);
